#include <unistd.h>

void	ft_print_numbers(void)
{
	char	i;

	i = '0';
	while (i <= '9')
	{
		write(1, &i, 1);
		i++;
	}
}

#ifdef TEST

int	main(void)
{
	ft_print_numbers();
	write(1, "\n", 1);
	return (0);
}

#endif
